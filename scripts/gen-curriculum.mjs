// Writes src/lib/path/curriculum.ts from the curriculum plan (curriculum.json in the knowledge vault):
// the grades, their units and the lessons a child can walk today (ready now, or ready after Phase 1),
// in curriculum order. Lessons still to be built are only counted per unit ("coming soon").
// Kept: grade, unit id/n/kid title, lesson id/seq/kid title/grown-up line/standard codes/prerequisites and
// what Keypals has for it (skills with :sub, Learn episodes, trips). Not kept: the reference curricula's
// unit titles and notes (the repo is public; Illustrative Mathematics is CC BY-NC).
//   node scripts/gen-curriculum.mjs [path/to/curriculum.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2] ?? join(homedir(), 'Documents/knowledge-vault/projects/ring2-products/keypals-curriculum/data/curriculum.json');
const out = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/path/curriculum.ts');
const d = JSON.parse(readFileSync(src, 'utf8'));
const phase1 = new Set(d.buildPlan.phase1.lessonIds);
const gradeNo = g => (g === 'K' ? 0 : Number(g));
const q = s => JSON.stringify(s);

const units = [], lessons = [];
for (const g of d.math) {
  for (const u of g.units) {
    const here = u.lessons.filter(l => l.status === 'have' || phase1.has(l.id));
    units.push(`  { id: ${q(u.id)}, grade: ${gradeNo(g.grade)}, n: ${u.n}, kidTitle: ${q(u.kidTitle)}, soon: ${u.lessons.length - here.length} },`);
    for (const l of here) {
      const k = l.keypalsToday;
      lessons.push(`  { id: ${q(l.id)}, seq: ${q(l.seq)}, unit: ${q(u.id)}, grade: ${gradeNo(g.grade)}, kidTitle: ${q(l.kidTitle)}, grownUp: ${q(l.grownUp)}, codes: ${q(l.codes)}, prerequisites: ${q(l.prerequisites)}, skills: ${q(k.skills)}, learn: ${q(k.learn)}, trips: ${q(k.trips)}, ready: ${q(l.status === 'have' ? 'now' : 'phase1')} },`);
    }
  }
}
const all = d.math.flatMap(g => g.units.flatMap(u => u.lessons));
const body = `// GENERATED by scripts/gen-curriculum.mjs from the Keypals curriculum plan (curriculum.json in the
// knowledge vault). Do not edit by hand: change the plan and run the script again. What the game does
// with each lesson (its practice, its Learn) is in lessonSpecs.ts, which is written by hand.
//
// The grades (K = 0), their units in curriculum order, and the lessons on a child's path today: the ones
// ready now and the ones Phase 1 makes ready by re-sorting what Keypals has. Lessons still to be built
// are only counted (\`soon\`), for the grown-ups' "coming soon".

export type CurUnit = { id: string; grade: number; n: number; kidTitle: string; soon: number };
export type CurLesson = {
  id: string; seq: string; unit: string; grade: number; kidTitle: string; grownUp: string;
  /** Common Core codes */
  codes: string[];
  /** the lessons it builds on (some are still to be built, so not on the path yet) */
  prerequisites: string[];
  /** what Keypals has for it: skills (\`skill:sub\` where only part fits), Learn episodes, practice trips */
  skills: string[]; learn: string[]; trips: string[];
  ready: 'now' | 'phase1';
};

export const CUR_UNITS: CurUnit[] = [
${units.join('\n')}
];

export const CUR_LESSONS: CurLesson[] = [
${lessons.join('\n')}
];

/** every lesson in the plan, built or not */
export const CUR_TOTAL = ${all.length};
`;
writeFileSync(out, body);
console.log(`wrote ${out}: ${units.length} units, ${lessons.length} lessons on the path, ${all.length} in the plan`);
